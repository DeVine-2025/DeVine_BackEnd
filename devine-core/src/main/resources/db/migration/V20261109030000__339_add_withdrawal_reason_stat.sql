-- 탈퇴 사유 통계(FUNC-MEM-003 5번)
-- 회원과 연결하지 않는다. member_id와 감사 칼럼(created_by에 clerk_id가 들어감) 없이 사유와 날짜만 남긴다.
CREATE TABLE withdrawal_reason_stat (
    withdrawal_reason_stat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason                    VARCHAR(30) NOT NULL,
    withdrawn_on              DATE        NOT NULL,
    CONSTRAINT withdrawal_reason_stat_reason_check
        CHECK (reason IN ('NO_USEFUL_FEATURE', 'MATCHING_UNSATISFIED', 'REPORT_UNSATISFIED', 'USING_OTHER_SERVICE', 'OTHER'))
);

CREATE INDEX idx_withdrawal_reason_stat_withdrawn_on ON withdrawal_reason_stat(withdrawn_on);
