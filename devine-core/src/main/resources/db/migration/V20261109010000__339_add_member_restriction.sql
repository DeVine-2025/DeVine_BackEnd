-- 정지·소명 중 탈퇴자 최소식별정보 보관(결정 C, FUNC-MEM-006)
-- 탈퇴일 + 1년 동안 이메일 해시로 재가입을 막고, 만료되면 FUNC-MEM-007 배치가 지운다.
-- 관리자 강제탈퇴(약관 제7조 5항 나)에서도 같은 테이블을 쓴다.
CREATE TABLE member_restriction (
    member_restriction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id             BIGINT       NOT NULL REFERENCES member(member_id),
    email_hash            VARCHAR(64)  NOT NULL,
    reason                TEXT,
    sanction_summary      TEXT,
    expires_at            TIMESTAMP(6) NOT NULL,
    created_at            TIMESTAMP(6) NOT NULL,
    updated_at            TIMESTAMP(6),
    created_by            VARCHAR(255),
    updated_by            VARCHAR(255)
);

CREATE INDEX idx_member_restriction_email_hash ON member_restriction(email_hash, expires_at);
CREATE INDEX idx_member_restriction_expires_at ON member_restriction(expires_at);
