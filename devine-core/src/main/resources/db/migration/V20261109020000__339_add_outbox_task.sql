-- 트랜잭션 커밋 뒤에 할 외부 작업 아웃박스
-- 탈퇴 트랜잭션 안에서 행을 만들고, 스케줄러가 커밋된 행만 꺼내 실행한다.
-- 성공한 행은 지운다(clerk_id 등 식별값을 남기지 않기 위해). 최종 실패 행은 FAILED로 남겨 운영자가 확인한다.
CREATE TABLE outbox_task (
    outbox_task_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type        VARCHAR(40)  NOT NULL,
    payload          TEXT         NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    attempt_count    INTEGER      NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMP(6) NOT NULL,
    last_error       VARCHAR(500),
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6),
    CONSTRAINT outbox_task_type_check
        CHECK (task_type IN ('GITHUB_GRANT_REVOKE', 'CLERK_USER_DELETE', 'S3_OBJECT_DELETE', 'WITHDRAWAL_REFUND_MAIL')),
    CONSTRAINT outbox_task_status_check
        CHECK (status IN ('PENDING', 'FAILED'))
);

CREATE INDEX idx_outbox_task_pending ON outbox_task(next_attempt_at) WHERE status = 'PENDING';
