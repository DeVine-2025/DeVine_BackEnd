CREATE TABLE complaint_evidence (
    complaint_evidence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id          BIGINT NOT NULL REFERENCES complaint(complaint_id),
    content               TEXT NOT NULL,
    created_at            TIMESTAMP(6) NOT NULL,
    updated_at            TIMESTAMP(6),
    created_by            VARCHAR(255),
    updated_by            VARCHAR(255)
);

CREATE UNIQUE INDEX uk_complaint_evidence_complaint ON complaint_evidence (complaint_id);
