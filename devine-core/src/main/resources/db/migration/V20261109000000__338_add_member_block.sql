CREATE TABLE member_block (
    member_block_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id BIGINT NOT NULL REFERENCES member(member_id),
    target_id BIGINT NOT NULL REFERENCES member(member_id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT uk_member_block_pair UNIQUE (blocker_id, target_id),
    CONSTRAINT ck_member_block_not_self CHECK (blocker_id <> target_id)
);
CREATE INDEX idx_member_block_target ON member_block(target_id, blocker_id);
